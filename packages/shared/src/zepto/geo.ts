/** State for a Zepto city (title-cased raw city in, state out). Unknown → "Other". */
export function stateOfCity(city: unknown): string {
  return CITY_STATE[normKey(city)] ?? 'Other';
}

/** Tidy the report's own spelling: ALL-CAPS cities (ALIGARH, MORADABAD…) → Title Case; keep mixed-case as-is. */
export function zpCity(raw: unknown): string {
  const s = String(raw ?? '')
    .trim()
    .replace(/\s+/g, ' ');
  if (!s) return 'Unknown';
  if (s !== s.toUpperCase()) return s;
  return s.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase());
}
